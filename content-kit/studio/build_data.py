#!/usr/bin/env python3
"""Inline every content asset into studio/data.js so the preview works even
when index.html is opened directly from disk (no fetch, no server needed).

Run after editing any deck, scene or prompt:
    python3 content-kit/studio/build_data.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
KIT = HERE.parent
DECKS = KIT / "carousels" / "decks"
BUILT = KIT / "carousels" / "build" / "index.json"
SCENES = KIT / "code-video" / "scenes.json"
PROMPTS = KIT / "code-video" / "prompts"

manifest = json.loads((DECKS / "index.json").read_text(encoding="utf-8"))
built = json.loads(BUILT.read_text(encoding="utf-8"))["decks"] if BUILT.exists() else {}

decks = []
for item in manifest["decks"]:
    d = json.loads((DECKS / item["file"]).read_text(encoding="utf-8"))
    decks.append({
        "id": d["id"], "account": d["account"], "handle": d["handle"],
        "title": d["title"], "title_text": d["slides"][0]["headline"],
        "pillar": d["pillar"], "keyword": d["keyword"], "language": d["language"],
        "goal": d["goal"], "caption_job": d["caption_job"],
        "slides": d["slides"], "caption": d["caption"],
        "hashtags": d["hashtags"], "first_comment": d["first_comment"],
        "alt": d["alt"], "sources": d["sources"], "claim_note": d["claim_note"],
        "images": ["../carousels/build/" + p for p in built.get(d["id"], {}).get("paths", [])],
    })

scenes = json.loads(SCENES.read_text(encoding="utf-8"))
prompt_map = {}
for p in sorted(PROMPTS.glob("*.txt")):
    prompt_map[p.name] = p.read_text(encoding="utf-8")

payload = {
    "generated": __import__("datetime").date.today().isoformat(),
    "decks": decks,
    "scenes": scenes["scenes"],
    "brand": scenes["brand"],
    "negative": scenes["common_negative"],
    "prompts": prompt_map,
    "video": "../code-video/samples/01-faida-offline.mp4",
    "poster": "../code-video/samples/still-01-hook.png",
    "stills": [
        "../code-video/samples/still-01-hook.png",
        "../code-video/samples/still-02-code.png",
        "../code-video/samples/still-03-receipt.png",
        "../code-video/samples/still-04-payoff.png",
    ],
}
out = HERE / "data.js"
out.write_text("/* generated by build_data.py - do not edit by hand */\n"
               "window.KIT_DATA = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
               encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size // 1024} KB, {len(decks)} decks, "
      f"{len(payload['scenes'])} scenes, {len(prompt_map)} prompts)")
